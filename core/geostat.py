def achieved_correlation(grid, values: Dict[str, np.ndarray], zone: Optional[int] = None) -> Dict[str, dict]:
    """Pearson and Spearman correlation between simulated properties over the active cells (optionally one zone)."""
    from scipy.stats import spearmanr
    m = grid.actnum > 0
    if zone is not None:
        m = m & np.broadcast_to((grid.layer_zone == zone)[:, None, None], m.shape)
    names = list(values)
    res = {}
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            x, y = values[a][m], values[b][m]
            if x.size > 2 and x.std() > 0 and y.std() > 0:
                sub = np.random.default_rng(0).choice(x.size, min(x.size, 20000), replace=False)
                res[f"{a}-{b}"] = dict(pearson=float(np.corrcoef(x, y)[0, 1]), spearman=float(spearmanr(x[sub], y[sub])[0]))
    return res


def exp_variogram(values: np.ndarray, mask: np.ndarray, axis: int, nlag: int = 20):
    """Experimental variogram (normalised by the variance) along array axis 0 = K, 1 = J, 2 = I."""
    v = values.astype(float)
    sel = v[mask]
    if sel.size < 10 or sel.std() == 0:
        return np.arange(1, nlag + 1), np.full(nlag, np.nan)
    v = (v - sel.mean()) / sel.std()
    n = v.shape[axis]
    lags, gam = [], []
    for h in range(1, min(nlag, n - 1) + 1):
        a = np.take(v, range(0, n - h), axis=axis)
        b = np.take(v, range(h, n), axis=axis)
        ma = np.take(mask, range(0, n - h), axis=axis) & np.take(mask, range(h, n), axis=axis)
        if ma.sum() > 10:
            lags.append(h)
            gam.append(0.5 * float(np.mean((a[ma] - b[ma]) ** 2)))
    return np.array(lags), np.array(gam)


def model_variogram(h_cells: np.ndarray, axis: int, spacing, row: dict, grid_angle: float = 0.0) -> np.ndarray:
    """Model variogram (normalised) along an axis for the lags ``h_cells``; ``spacing`` = (dx, dy, dz)."""
    d = np.asarray(h_cells, float) * spacing[{2: 0, 1: 1, 0: 2}[axis]]
    zero = np.zeros_like(d)
    du, dv, dw = (d, zero, zero) if axis == 2 else (zero, d, zero) if axis == 1 else (zero, zero, d)
    rho = lag_corr(du, dv, dw, row["vtype"], row["major"], row["minor"], row["vert"], rel_angle(row["azimuth"], grid_angle))
    nug = float(row.get("nugget", 0.0))
    return nug + (1 - nug) * (1 - rho)
