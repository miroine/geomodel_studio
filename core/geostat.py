"""Stochastic property modelling on the 3D grid: Gaussian random fields with a variogram, target histograms,
cross-correlation and net / gross cut-offs.

Workflow (per zone, per realisation)
------------------------------------
1. For every simulated property (PORO, PERM, NTG) draw an independent standard-normal random field with the
   zone's variogram (spherical / exponential / gaussian, major / minor / vertical range, azimuth, nugget).  The
   field is generated by spectral simulation (FFT circulant embedding) in cell-index space scaled by the mean
   cell size, so it is fast for millions of cells.
2. Impose the cross-correlation: the fields are mixed with the Cholesky factor of the correlation matrix
   (collocated co-simulation - the correlation is that of the Gaussian "normal scores").
3. Transform each field to the target histogram of the zone (normal / log-normal / uniform / triangular /
   user histogram bins / pasted values) with a rank (normal-score) transform, then truncate at min / max.
4. Permeability can alternatively be computed from porosity: log10(k) = a * PORO + b + scatter field.
5. Cut-offs (porosity, permeability, NTG) define the NET flag; NTG can be zeroed in non-net cells or replaced by
   the binary net flag.  PERMY = kykx * PERMX and PERMZ = kvkh(zone) * PERMX.

Limits: spacings use the mean cell size (non-uniform / refined grids are treated as uniform in the field
generation), zones are simulated independently (no continuity across zone boundaries), no conditioning to wells.
"""
from __future__ import annotations

from typing import Dict, List, Optional
import numpy as np
from scipy.fft import next_fast_len
from scipy.special import ndtri, ndtr

VARIOGRAMS = ["spherical", "exponential", "gaussian"]
DISTS = ["normal", "lognormal", "uniform", "triangular", "histogram", "values"]
DIST_PARAMS = {                      # labels of (p1, p2, p3)
    "normal": ("mean", "std", ""), "lognormal": ("median", "ln-sigma", ""), "uniform": ("min", "max", ""),
    "triangular": ("min", "mode", "max"), "histogram": ("", "", ""), "values": ("", "", "")}
PROPS = ["PORO", "PERM", "NTG"]


class GeostatError(Exception):
    pass


# ---------------------------------------------------------------- variogram model
def corr_value(h: np.ndarray, vtype: str) -> np.ndarray:
    """Correlation (1 - normalised variogram) at scaled distance h (h = 1 at the practical range)."""
    h = np.asarray(h, float)
    if vtype == "spherical":
        return np.where(h < 1.0, 1.0 - 1.5 * h + 0.5 * h ** 3, 0.0)
    if vtype == "exponential":
        return np.exp(-3.0 * h)
    if vtype == "gaussian":
        return np.exp(-3.0 * h * h)
    raise GeostatError(f"Unknown variogram '{vtype}'")


def lag_corr(du, dv, dw, vtype, major, minor, vert, rel_deg):
    """Correlation for lag components along I (du), J (dv) and K (dw); ``rel_deg`` = major direction ccw from the I axis."""
    c, s = np.cos(np.deg2rad(rel_deg)), np.sin(np.deg2rad(rel_deg))
    a = (du * c + dv * s) / max(major, 1e-9)
    b = (-du * s + dv * c) / max(minor, 1e-9)
    d = dw / max(vert, 1e-9)
    return corr_value(np.sqrt(a * a + b * b + d * d), vtype)


def rel_angle(azimuth_deg: float, grid_angle_deg: float = 0.0) -> float:
    """Major-axis azimuth (degrees clockwise from north, world) -> angle ccw from the grid's I axis."""
    return (90.0 - float(azimuth_deg)) - float(grid_angle_deg)


def gaussian_field(shape, spacing, vp: dict, rng: np.random.Generator, rel_deg: float) -> np.ndarray:
    """Standardised (mean 0, std 1) Gaussian random field of ``shape`` = (nk, nj, ni) by spectral simulation."""
    nk, nj, ni = shape
    dx, dy, dz = spacing
    rng_cells = (max(vp["major"], vp["minor"]) / dx, max(vp["major"], vp["minor"]) / dy, vp["vert"] / dz)
    M = [next_fast_len(int(n + min(np.ceil(r), n))) for n, r in zip((nk, nj, ni), (rng_cells[2], rng_cells[1], rng_cells[0]))]
    lag = lambda m, d: (np.minimum(np.arange(m), m - np.arange(m)) * d).astype(float)
    LZ, LY, LX = lag(M[0], dz)[:, None, None], lag(M[1], dy)[None, :, None], lag(M[2], dx)[None, None, :]
    C = lag_corr(LX, LY, LZ, vp["vtype"], vp["major"], vp["minor"], vp["vert"], rel_deg)
    S = np.fft.rfftn(C).real
    S = np.maximum(S, 0.0)
    W = rng.standard_normal(M)
    f = np.fft.irfftn(np.fft.rfftn(W) * np.sqrt(S), s=M)[:nk, :nj, :ni]
    f = (f - f.mean()) / (f.std() + 1e-12)
    nug = float(np.clip(vp.get("nugget", 0.0), 0.0, 1.0))
    if nug > 0:
        f = np.sqrt(1.0 - nug) * f + np.sqrt(nug) * rng.standard_normal(f.shape)
        f = (f - f.mean()) / (f.std() + 1e-12)
    return f


# ---------------------------------------------------------------- distributions
def quantile(dist: str, u: np.ndarray, row: dict, extra: Optional[dict] = None) -> np.ndarray:
    """Quantile function of the target distribution for probabilities ``u`` in (0, 1)."""
    extra = extra or {}
    u = np.clip(u, 1e-9, 1 - 1e-9)
    p1, p2, p3 = (float(row.get(k, 0.0) or 0.0) for k in ("p1", "p2", "p3"))
    if dist == "normal":
        return p1 + p2 * ndtri(u)
    if dist == "lognormal":
        if p1 <= 0:
            raise GeostatError("Log-normal needs a positive median.")
        return p1 * np.exp(p2 * ndtri(u))
    if dist == "uniform":
        return p1 + (p2 - p1) * u
    if dist == "triangular":
        a, c, b = p1, p2, p3
        if not (a <= c <= b) or b <= a:
            raise GeostatError("Triangular needs min <= mode <= max.")
        fc = (c - a) / (b - a)
        return np.where(u < fc, a + np.sqrt(u * (b - a) * (c - a)), b - np.sqrt((1 - u) * (b - a) * (b - c)))
    if dist == "histogram":
        bins = extra.get("bins") or []
        lo = np.array([b[0] for b in bins], float)
        hi = np.array([b[1] for b in bins], float)
        w = np.array([b[2] for b in bins], float)
        ok = (w > 0) & (hi > lo)
        if not ok.any():
            raise GeostatError("The histogram needs at least one bin with weight > 0 and upper > lower.")
        lo, hi, w = lo[ok], hi[ok], w[ok]
        o = np.argsort(lo)
        lo, hi, w = lo[o], hi[o], w[o] / w.sum()
        cum = np.concatenate([[0.0], np.cumsum(w)])
        k = np.clip(np.searchsorted(cum, u, side="right") - 1, 0, len(w) - 1)
        return lo[k] + (u - cum[k]) / w[k] * (hi[k] - lo[k])
    if dist == "values":
        v = np.sort(np.asarray(extra.get("values") or [], float))
        v = v[np.isfinite(v)]
        if v.size < 3:
            raise GeostatError("Give at least 3 values for an empirical distribution.")
        return np.interp(u, (np.arange(v.size) + 0.5) / v.size, v)
    raise GeostatError(f"Unknown distribution '{dist}'")


def parse_values(text: str) -> List[float]:
    out = []
    for t in str(text).replace(";", ",").replace("\n", ",").replace("\t", ",").replace(" ", ",").split(","):
        t = t.strip()
        if t:
            try:
                out.append(float(t))
            except ValueError:
                raise GeostatError(f"'{t}' is not a number.") from None
    return out


def rank_uniform(x: np.ndarray) -> np.ndarray:
    """Rank transform to (0, 1) preserving order (ties broken by position)."""
    flat = x.ravel()
    r = np.empty(flat.size)
    r[np.argsort(flat, kind="stable")] = (np.arange(flat.size) + 0.5) / flat.size
    return r.reshape(x.shape)


# ---------------------------------------------------------------- configuration
def default_config(grid) -> dict:
    """Starting configuration from the grid's zone table (porosity / permeability / NTG constants become the means)."""
    dxm, dym = float(np.mean(np.diff(grid.xs))), float(np.mean(np.diff(grid.ys)))
    dzm = float(np.mean(grid.thickness()[grid.actnum > 0])) if (grid.actnum > 0).any() else 1.0
    vg = dict(vtype="spherical", major=round(8 * dxm, -1) or 1.0, minor=round(5 * dym, -1) or 1.0, vert=round(max(3 * dzm, 1.0), 1), azimuth=0.0, nugget=0.05)
    cfg = dict(seed=42, nreal=1, perm_mode="field", transform=dict(a=12.0, b=-1.5, sigma=0.3), kykx=1.0, use_kvkh=True,
               corr=dict(PORO_PERM=0.7, PORO_NTG=0.5, PERM_NTG=0.35),
               cut=dict(phi=0.0, k=0.0, ntg=0.0, apply=True, binary=False),
               props={})
    for pr in PROPS:
        rows = []
        for z in grid.zones:
            if pr == "PORO":
                r = dict(p1=z.poro, p2=max(0.1 * z.poro, 0.01), p3=0.0, vmin=0.0, vmax=0.45)
            elif pr == "PERM":
                r = dict(p1=max(z.permx, 0.01), p2=0.8, p3=0.0, vmin=0.0, vmax=1e6)
            else:
                r = dict(p1=z.ntg, p2=0.1, p3=0.0, vmin=0.0, vmax=1.0)
            r.update(zone=z.name, simulate=True, **vg)
            rows.append(r)
        cfg["props"][pr] = dict(enabled=True, dist="lognormal" if pr == "PERM" else "normal", rows=rows, bins=[], values=[])
    return cfg


def corr_matrix(cfg: dict, names: List[str]) -> np.ndarray:
    c = cfg["corr"]
    R = np.eye(len(names))
    for i, a in enumerate(names):
        for j, b in enumerate(names):
            if i < j:
                R[i, j] = R[j, i] = float(c.get(f"{a}_{b}", c.get(f"{b}_{a}", 0.0)))
    return R


def check_config(cfg: dict) -> List[str]:
    errs = []
    names = [p for p in PROPS if cfg["props"][p]["enabled"]]
    if not names:
        errs.append("Enable at least one property.")
    if cfg["perm_mode"] == "transform" and "PERM" in names and "PORO" not in names:
        errs.append("Permeability from porosity needs PORO to be simulated.")
    fld = [n for n in names if not (n == "PERM" and cfg["perm_mode"] == "transform")]
    if len(fld) > 1:
        R = corr_matrix(cfg, fld)
        if np.linalg.eigvalsh(R).min() < 1e-9:
            errs.append("The correlation matrix is not positive definite - lower the correlations (e.g. PORO-PERM and PORO-NTG high needs PERM-NTG high as well).")
    for n in names:
        for r in cfg["props"][n]["rows"]:
            if r["simulate"] and (r["major"] <= 0 or r["minor"] <= 0 or r["vert"] <= 0):
                errs.append(f"{n} / {r['zone']}: variogram ranges must be positive.")
            if r["vmax"] <= r["vmin"]:
                errs.append(f"{n} / {r['zone']}: max must exceed min.")
    return errs


# ---------------------------------------------------------------- the workflow
def simulate(grid, cfg: dict, progress=None, cond: Optional[Dict[str, np.ndarray]] = None) -> Dict[str, dict]:
    """Run the stochastic workflow.  Returns {name: dict(values (nk,nj,ni), kind, unit)} for all realisations.

    ``cond`` = {"PORO"|"PERM"|"NTG": blocked-well array (nk,nj,ni), NaN = no data} conditions the realisations: the Gaussian
    field is conditioned by kriging (scores of the data in the target distribution) and the data values are honoured
    exactly in their cells.  PERM is not conditioned when it is derived from porosity ("transform" mode).
    """
    errs = check_config(cfg)
    if errs:
        raise GeostatError(" ".join(errs))
    shape = (grid.nk, grid.nj, grid.ni)
    act = grid.actnum > 0
    th = grid.thickness()
    dx, dy = float(np.mean(np.diff(grid.xs))), float(np.mean(np.diff(grid.ys)))
    names = [p for p in PROPS if cfg["props"][p]["enabled"]]
    tmode = cfg["perm_mode"] == "transform" and "PERM" in names
    field_names = [n for n in names if not (n == "PERM" and tmode)]
    out: Dict[str, dict] = {}
    nreal = int(max(1, cfg["nreal"]))
    for r in range(nreal):
        sfx = f"_R{r + 1}" if nreal > 1 else ""
        vals = {n: np.full(shape, np.nan) for n in names}
        for zi, z in enumerate(grid.zones):
            ks = np.where(grid.layer_zone == zi)[0]
            if ks.size == 0:
                continue
            am = act[ks]
            dz = float(th[ks][am].mean()) if am.any() else 1.0
            dz = max(dz, 1e-3)
            rows = {n: next((q for q in cfg["props"][n]["rows"] if q["zone"] == z.name), None) for n in names}
            ss = np.random.SeedSequence([int(cfg["seed"]), r, zi])
            gens = [np.random.default_rng(s) for s in ss.spawn(len(PROPS) + 1)]
            fields = {}
            for n in names:
                row = rows[n]
                if row is None or not row["simulate"]:
                    continue
                fields[n] = gaussian_field((ks.size, grid.nj, grid.ni), (dx, dy, dz), row,
                                           gens[PROPS.index(n)], rel_angle(row["azimuth"], grid.angle))
            ff = [n for n in field_names if n in fields]
            if len(ff) > 1:                                         # impose the correlation (sub-matrix of the full Cholesky problem)
                Ls = np.linalg.cholesky(corr_matrix(cfg, ff))
                stack = np.stack([fields[n] for n in ff])
                mixed = np.tensordot(Ls, stack, axes=(1, 0))
                for i, n in enumerate(ff):
                    fields[n] = mixed[i]
            exact = {}
            if cond:
                uc_ = 0.5 * (grid.xs[:-1] + grid.xs[1:])
                vc_ = 0.5 * (grid.ys[:-1] + grid.ys[1:])
                for n in list(fields):
                    arr = cond.get(n)
                    if arr is None or (n == "PERM" and tmode):
                        continue
                    sub_ = arr[ks]
                    kk, jj, ii = np.where(~np.isnan(sub_))
                    if kk.size == 0:
                        continue
                    d = sub_[kk, jj, ii].astype(float)
                    pc = cfg["props"][n]
                    ds = prob_scores(pc["dist"], rows[n], dict(bins=pc["bins"], values=pc["values"]), d)
                    fields[n] = condition_field(fields[n], kk, jj, ii, ds, uc_, vc_, dz, rows[n], rel_angle(rows[n]["azimuth"], grid.angle))
                    exact[n] = (kk, jj, ii, d)
            tmp = {}
            for n in names:
                if n not in fields and not (n == "PERM" and tmode):
                    continue
                pcfg = cfg["props"][n]
                row = rows[n]
                if n == "PERM" and tmode:
                    t = cfg["transform"]
                    sc = fields.get(n)
                    if sc is None:
                        sc = gaussian_field((ks.size, grid.nj, grid.ni), (dx, dy, dz), row, gens[PROPS.index(n)], rel_angle(row["azimuth"], grid.angle))
                    poro = tmp.get("PORO")
                    if poro is None:
                        raise GeostatError("Permeability from porosity needs PORO simulated in every zone.")
                    v = 10.0 ** (float(t["a"]) * poro + float(t["b"]) + float(t["sigma"]) * sc)
                else:
                    u = ndtr(fields[n]) if n in exact else rank_uniform(fields[n])
                    v = quantile(pcfg["dist"], u, row, dict(bins=pcfg["bins"], values=pcfg["values"]))
                v = np.clip(v, row["vmin"] if row else -np.inf, row["vmax"] if row else np.inf)
                if n in exact:
                    kk, jj, ii, d = exact[n]
                    v = np.array(v, float)
                    v[kk, jj, ii] = d
                tmp[n] = v
            for n, v in tmp.items():
                vals[n][ks] = v
            if progress:
                progress((r * len(grid.zones) + zi + 1) / (nreal * len(grid.zones)))
        for n in names:
            vals[n] = np.where(np.isnan(vals[n]), 0.0, vals[n])
        units = dict(PORO="frac", PERM="mD", NTG="frac")
        res = {}
        if "PORO" in vals:
            res["PORO"] = (vals["PORO"], "continuous")
        if "PERM" in vals:
            kx = vals["PERM"]
            res["PERMX"] = (kx, "continuous")
            res["PERMY"] = (kx * float(cfg["kykx"]), "continuous")
            kv = np.ones(shape)
            if cfg["use_kvkh"]:
                for zi, z in enumerate(grid.zones):
                    kv[grid.layer_zone == zi] = z.kvkh
            res["PERMZ"] = (kx * kv, "continuous")
        if "NTG" in vals:
            res["NTG"] = (np.clip(vals["NTG"], 0.0, 1.0), "continuous")
        c = cfg["cut"]
        net = np.ones(shape, bool)
        used = False
        if c["phi"] > 0 and "PORO" in vals:
            net &= vals["PORO"] >= c["phi"]
            used = True
        if c["k"] > 0 and "PERM" in vals:
            net &= vals["PERM"] >= c["k"]
            used = True
        if c["ntg"] > 0 and "NTG" in vals:
            net &= vals["NTG"] >= c["ntg"]
            used = True
        if used:
            res["NET"] = (net.astype(float), "discrete")
            if c["apply"]:
                if "NTG" in res and not c["binary"]:
                    res["NTG"] = (np.where(net, res["NTG"][0], 0.0), "continuous")
                else:
                    res["NTG"] = (net.astype(float), "continuous")
        for n, (v, kind) in res.items():
            u_ = {"PORO": "frac", "NTG": "frac", "NET": ""}.get(n, "mD")
            out[n + sfx] = dict(values=v, kind=kind, unit=u_)
    return out



# ---------------------------------------------------------------- kriging / conditioning
def _scaled(u, v, w, vp: dict, rel_deg: float) -> np.ndarray:
    """Coordinates divided by the anisotropy ranges so that the Euclidean distance equals the scaled lag h."""
    c, s = np.cos(np.deg2rad(rel_deg)), np.sin(np.deg2rad(rel_deg))
    a = (u * c + v * s) / max(vp["major"], 1e-9)
    b = (-u * s + v * c) / max(vp["minor"], 1e-9)
    d = w / max(vp["vert"], 1e-9)
    return np.column_stack([a, b, d])


def simple_krige(dpos: np.ndarray, dval: np.ndarray, tpos: np.ndarray, vp: dict, nmax: int = 12,
                 chunk: int = 4000) -> np.ndarray:
    """Simple kriging (mean 0, unit sill) of ``dval`` at ``tpos``.  Positions are already scaled (see :func:`_scaled`).

    Neighbourhood = the ``nmax`` nearest data within one practical range (scaled distance 1); targets without a
    neighbour get 0.  The covariance is ``(1 - nugget) * rho(h)`` with a nugget on the data diagonal.
    """
    from scipy.spatial import cKDTree
    nd = len(dval)
    out = np.zeros(len(tpos))
    if nd == 0 or len(tpos) == 0:
        return out
    nug = float(np.clip(vp.get("nugget", 0.0), 0.0, 0.99))
    vt = vp["vtype"]
    tree = cKDTree(dpos)
    m = min(nmax, nd)
    dist, idx = tree.query(tpos, k=m, distance_upper_bound=1.0)
    for a in range(0, len(tpos), chunk):
        sl = slice(a, a + chunk)
        di, ii = dist[sl], idx[sl]
        valid = np.isfinite(di)                                  # missing neighbours have idx == nd and dist == inf
        has = valid.any(axis=1)
        if not has.any():
            continue
        ii, di, valid = ii[has], di[has], valid[has]
        iic = np.where(valid, ii, 0)
        P = dpos[iic]                                           # (n, m, 3)
        H = np.sqrt(((P[:, :, None, :] - P[:, None, :, :]) ** 2).sum(-1))
        C = (1.0 - nug) * corr_value(H, vt)
        eye = np.eye(m)[None]
        C = C + nug * eye
        vm = valid[:, :, None] & valid[:, None, :]
        C = np.where(vm, C, eye)                                # missing neighbours: identity row, zero rhs
        c0 = np.where(valid, (1.0 - nug) * corr_value(np.where(valid, di, 2.0), vt), 0.0)
        C = C + 1e-9 * eye
        w = np.linalg.solve(C, c0[:, :, None])[:, :, 0]
        est = (w * np.where(valid, dval[iic], 0.0)).sum(axis=1)
        sub = np.zeros(len(has))
        sub[has] = est
        out[sl] = sub
    return out


def normal_score(values: np.ndarray):
    """Rank-based normal-score transform.  Returns (scores, sorted values, sorted scores) for the back-transform."""
    from scipy.special import ndtri, ndtr
    v = np.asarray(values, float)
    n = len(v)
    order = np.argsort(v, kind="stable")
    p = (np.arange(n) + 0.5) / n
    sc = np.empty(n)
    sc[order] = ndtri(p)
    return sc, v[order], ndtri(p)


def back_transform(scores: np.ndarray, sorted_vals: np.ndarray, sorted_scores: np.ndarray) -> np.ndarray:
    if len(sorted_vals) == 1:
        return np.full(np.shape(scores), sorted_vals[0])
    return np.interp(scores, sorted_scores, sorted_vals)


def prob_scores(dist: str, row: dict, extra: dict, data: np.ndarray) -> np.ndarray:
    """Normal scores of ``data`` with respect to the target distribution of the stochastic workflow."""
    from scipy.special import ndtri, ndtr
    uu = (np.arange(4001) + 0.5) / 4001
    qv = quantile(dist, uu, row, extra)
    qv = np.maximum.accumulate(qv) + np.arange(qv.size) * 1e-12 * max(1.0, float(np.abs(qv).max()))
    u = np.interp(data, qv, uu)
    return ndtri(np.clip(u, 0.001, 0.999))


def krige_property(grid, blocked: np.ndarray, vp: dict, rel_deg: float, by_zone: bool = True, nmax: int = 12,
                   nscore: bool = True, progress=None) -> np.ndarray:
    """Simple kriging of blocked well data to every active cell (per zone), in the normal-score domain.

    Cells beyond the range of any datum keep the data mean (the simple-kriging mean).  Returns (nk, nj, ni) float32.
    """
    out = np.full(blocked.shape, np.nan, np.float32)
    act = grid.actnum > 0
    uc = 0.5 * (grid.xs[:-1] + grid.xs[1:])
    vc = 0.5 * (grid.ys[:-1] + grid.ys[1:])
    th = grid.thickness()
    groups = [(zi, np.where(grid.layer_zone == zi)[0]) for zi in range(len(grid.zones))] if by_zone else [(None, np.arange(grid.nk))]
    for gi, (zi, ks) in enumerate(groups):
        if ks.size == 0:
            continue
        am = act[ks]
        dz = max(float(th[ks][am].mean()) if am.any() else 1.0, 1e-3)
        sub = blocked[ks]
        kk, jj, ii = np.where(~np.isnan(sub))
        if kk.size == 0:
            continue
        val = sub[kk, jj, ii].astype(float)
        if nscore and kk.size >= 3:
            sc, sv, ss = normal_score(val)
        else:
            sc, sv, ss = (val - val.mean()) / (val.std() + 1e-12), None, None
        dpos = _scaled(uc[ii], vc[jj], kk * dz, vp, rel_deg)
        tk, tj, ti = np.where(am)
        tpos = _scaled(uc[ti], vc[tj], tk * dz, vp, rel_deg)
        est = simple_krige(dpos, sc, tpos, vp, nmax)
        if sv is not None:
            res = back_transform(est, sv, ss)
        else:
            res = est * (val.std() + 1e-12) + val.mean()
        o = np.full(sub.shape, np.nan, np.float32)
        o[tk, tj, ti] = res
        out[ks] = o
        if progress:
            progress((gi + 1) / len(groups))
    return out


def condition_field(f: np.ndarray, dk, dj, di, dscore: np.ndarray, uc, vc, dz: float, vp: dict, rel_deg: float, nmax=12):
    """Conditioning by kriging: ``f_c = f + SK(dscore - f[data])`` for a standardised field ``f`` (nk, nj, ni)."""
    if len(dscore) == 0:
        return f
    resid = dscore - f[dk, dj, di]
    dpos = _scaled(uc[di], vc[dj], dk * dz, vp, rel_deg)
    nk, nj, ni = f.shape
    tk, tj, ti = np.indices((nk, nj, ni)).reshape(3, -1)
    tpos = _scaled(uc[ti], vc[tj], tk * dz, vp, rel_deg)
    corr = simple_krige(dpos, resid, tpos, vp, nmax)
    return f + corr.reshape(f.shape)

